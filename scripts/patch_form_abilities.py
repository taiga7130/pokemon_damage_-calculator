# 模様・色違いのみのフォルム（特性は種で共通）
VIVILLON = ["りんぷん", "ふくがん", "フレンドガード"]
FLORGES = ["フラワーベール", "きょうせい"]
FURFROU = ["ファーコート"]
GOURGEIST = ["ものひろい", "おみとおし", "ふみん"]
ALCREMIE = ["スイートベール", "アロマベール"]


def abilities_for(dex: int, form_name: str) -> list[str] | None:
    if (dex, form_name) in PATCH:
        return PATCH[(dex, form_name)]
    if dex == 666 and form_name.startswith("ビビヨン("):
        return VIVILLON
    if dex == 671 and form_name.startswith("フラージェス("):
        return FLORGES
    if dex == 676 and form_name.startswith("トリミアン("):
        return FURFROU
    if dex == 711 and form_name.startswith("パンプジン("):
        return GOURGEIST
    if dex == 869 and form_name.startswith("マホイップ("):
        return ALCREMIE
    return None


def main() -> None:
    with open(DATA, encoding="utf-8") as f:
        data = json.load(f)

    patched, still_missing = 0, []
    for p in data:
        for form in p["forms"]:
            if form.get("abilities") is not None:
                continue  # ベース等、収録済みは触らない
            fill = abilities_for(p["dexNo"], form["formName"])
            if fill is not None:
                form["abilities"] = fill
                patched += 1
            else:
                still_missing.append(
                    {"dexNo": p["dexNo"], "formName": form["formName"], "formType": form["formType"]}
                )

    with open(DATA, "w", encoding="utf-8") as f:
        json.dump(data, f, ensure_ascii=False, indent=1)
        f.write("\n")
    with open(COMPLETION, "w", encoding="utf-8") as f:
        json.dump(still_missing, f, ensure_ascii=False, indent=1)
        f.write("\n")

    print(f"補完: {patched} フォルム / 未収録のまま: {len(still_missing)}")
    for m in still_missing:
        print("  ", m)


if __name__ == "__main__":
    main()
